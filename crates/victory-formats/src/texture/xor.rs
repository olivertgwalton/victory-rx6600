/// The equation of a XOR mode for an element size, sample count and
/// dimension (1D uses the 2D one); `None` where the library has none.
pub(crate) fn equation(
    swizzle: super::Swizzle,
    element_log2: u32,
    samples: u32,
    volume: bool,
) -> Option<&'static Equation> {
    EQUATIONS.iter().find(|e| {
        u32::from(e.swizzle) == swizzle.0
            && u32::from(e.element_log2) == element_log2
            && u32::from(e.samples_log2) == samples.trailing_zeros()
            && e.volume == volume
    })
}
