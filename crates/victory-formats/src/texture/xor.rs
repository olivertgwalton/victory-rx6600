/// The equation of a XOR mode for an element size, sample count and
/// dimension (1D uses the 2D one); `None` where the library has none.
pub(crate) fn equation(
    swizzle: super::Swizzle,
    element_log2: u32,
    samples: u32,
    volume: bool,
    series_s: bool,
) -> Option<&'static Equation> {
    if series_s {
        return series_s_equations().iter().find(|e| {
            u32::from(e.swizzle) == swizzle.0
                && u32::from(e.element_log2) == element_log2
                && u32::from(e.samples_log2) == samples.trailing_zeros()
                && e.volume == volume
        });
    }
    EQUATIONS.iter().find(|e| {
        u32::from(e.swizzle) == swizzle.0
            && u32::from(e.element_log2) == element_log2
            && u32::from(e.samples_log2) == samples.trailing_zeros()
            && e.volume == volume
    })
}

/// The Series S equations (the library after `XGSetHardwareVersion(4)`),
/// single-sampled: from the terms `tools/xg-terms` read out of it
/// (`crate::texture_xor`, whose Series X terms are these equations').
/// shortcut: no Series S multisampled equations; add them from the library
/// when a Series S title copies one.
fn series_s_equations() -> &'static [Equation] {
    static ALL: std::sync::OnceLock<Vec<Equation>> = std::sync::OnceLock::new();
    ALL.get_or_init(|| {
        crate::texture_xor::XOR_TERMS
            .iter()
            .filter(|t| t.0)
            .map(|&(_, swizzle, volume, element_log2, x, y, z)| Equation {
                swizzle,
                element_log2,
                samples_log2: 0,
                volume,
                // bit 13 has no term in any mode
                x: std::array::from_fn(|i| x[i]),
                y: std::array::from_fn(|i| y[i]),
                z,
                s: [0; 3],
            })
            .collect()
    })
}
